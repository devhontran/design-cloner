  const cardShadow = card?.shadow ? (dna.elevation.shadows.md ? 'var(--shadow-md)' : card.shadow) : (dna.elevation.separation === 'shadows' && dna.elevation.shadows.md ? 'var(--shadow-md)' : 'none');
