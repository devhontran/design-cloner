// DNA -> design tokens: CSS variables, Tailwind v4 @theme, Tailwind v3 preset, DTCG JSON, component CSS.
import { googleFontsUrl } from '../lib/fonts.js';

const q = (name) => (/\s/.test(name) ? `"${name}"` : name);
const fontStack = (f) => (f ? `${q(f.use || f.name)}, ${f.fallback}` : 'ui-sans-serif, system-ui, sans-serif');
const em = (v) => `${Math.round((v || 0) * 1000) / 1000}em`;

/** Flat token map shared by every output format. Keys follow Tailwind v4 namespaces. */
export function tokenMap(dna) {
  const c = dna.color, t = dna.typography, s = dna.spacing;
  const tokens = {};
  for (const [k, v] of Object.entries(c.roles)) tokens[`color-${k}`] = v;
  for (const [rampName, steps] of Object.entries(c.ramps)) for (const [step, v] of Object.entries(steps)) tokens[`color-${rampName}-${step}`] = v;
  tokens['font-display'] = fontStack(t.families.display);
  tokens['font-body'] = fontStack(t.families.body);
  tokens['font-sans'] = tokens['font-body'];
  if (t.families.ui) tokens['font-ui'] = fontStack(t.families.ui);
  if (t.families.mono) tokens['font-mono'] = fontStack(t.families.mono);
  for (const [k, v] of Object.entries(t.scale)) tokens[`text-${k}`] = `${v / 16}rem`;
  tokens['font-weight-body'] = String(t.body.weight);
  tokens['font-weight-heading'] = String(t.headings.h2.weight || t.headings.h1.weight);
  tokens['font-weight-display'] = String(t.headings.h1.weight);
  tokens['leading-body'] = String(t.body.lineHeight);
  tokens['leading-heading'] = String(t.headings.h2.lineHeight || 1.2);
  tokens['leading-display'] = String(t.headings.h1.lineHeight || 1.1);
  tokens['tracking-display'] = em(t.headings.h1.letterSpacing);
  tokens['tracking-heading'] = em(t.headings.h2.letterSpacing);
  if (t.eyebrow) tokens['tracking-eyebrow'] = em(t.eyebrow.letterSpacing);
  tokens.spacing = `${s.unit / 16}rem`;
  s.scale.forEach((v, i) => { tokens[`space-${i + 1}`] = `${v / 16}rem`; });
  tokens['section-y'] = `${s.sectionY / 16}rem`;
  tokens['container'] = `${s.container}px`;
  tokens['gutter'] = `${s.gutter}px`;
  for (const [k, v] of Object.entries(dna.shape.radius)) tokens[`radius-${k}`] = v >= 9999 ? '9999px' : `${v}px`;
  for (const [k, v] of Object.entries(dna.elevation.shadows || {})) tokens[`shadow-${k}`] = v;
  tokens['duration'] = `${dna.motion.duration}ms`;
  tokens['ease-brand'] = dna.motion.easing;
  if (dna.color.gradients?.[0]) tokens['gradient-brand'] = dna.color.gradients[0];
  return tokens;
}

const header = (dna) => `/* Design DNA "${dna.name}" — generated by design-cloner. Personality: ${dna.personality.keywords.join(', ')} */`;

export function fontImport(dna) {
  const f = dna.typography.families;
  const url = googleFontsUrl([f.display, f.body, f.ui, f.mono].filter(Boolean));
  return url ? `@import url('${url}');\n` : '';
}

export function toCss(dna) {
  const tokens = tokenMap(dna);
  const lines = Object.entries(tokens).map(([k, v]) => `  --${k}: ${v};`);
  return `${header(dna)}\n${fontImport(dna)}\n:root {\n  color-scheme: ${dna.color.mode};\n${lines.join('\n')}\n}\n`;
}

export function toTailwindV4(dna) {
  const tokens = tokenMap(dna);
  const skip = new Set(['section-y', 'container', 'gutter', 'duration', 'gradient-brand']);
  const theme = Object.entries(tokens).filter(([k]) => !skip.has(k) && !k.startsWith('space-')).map(([k, v]) => `  --${k}: ${v};`);
  const extra = Object.entries(tokens).filter(([k]) => skip.has(k) || k.startsWith('space-')).map(([k, v]) => `  --${k}: ${v};`);
  return `${header(dna)}\n/* Tailwind CSS v4: @import "tailwindcss"; then @import "./tailwind-v4.css"; */\n${fontImport(dna)}\n@theme {\n${theme.join('\n')}\n}\n\n:root {\n${extra.join('\n')}\n}\n`;
}

export function toTailwindPreset(dna) {
  const c = dna.color, t = dna.typography;
  const colors = {};
  for (const [k, v] of Object.entries(c.roles)) colors[k] = v;
  for (const [name, steps] of Object.entries(c.ramps)) colors[name] = { ...steps, DEFAULT: c.roles[name] || steps[500] };
  const fontSize = Object.fromEntries(Object.entries(t.scale).map(([k, v]) => [k, `${v / 16}rem`]));
  const spacing = Object.fromEntries(dna.spacing.scale.map((v) => [String(v / 4), `${v / 16}rem`]));
  const preset = {
    theme: {
      extend: {
        colors,
        fontFamily: {
          display: fontStack(t.families.display).split(/,\s*/),
          sans: fontStack(t.families.body).split(/,\s*/),
          ...(t.families.ui ? { ui: fontStack(t.families.ui).split(/,\s*/) } : {}),
          ...(t.families.mono ? { mono: fontStack(t.families.mono).split(/,\s*/) } : {}),
        },
        fontSize,
        spacing,
        borderRadius: Object.fromEntries(Object.entries(dna.shape.radius).map(([k, v]) => [k, v >= 9999 ? '9999px' : `${v}px`])),
        boxShadow: dna.elevation.shadows || {},
        maxWidth: { container: `${dna.spacing.container}px` },
        letterSpacing: { display: em(t.headings.h1.letterSpacing), heading: em(t.headings.h2.letterSpacing) },
        lineHeight: { display: String(t.headings.h1.lineHeight), body: String(t.body.lineHeight) },
        transitionDuration: { DEFAULT: `${dna.motion.duration}ms` },
        transitionTimingFunction: { brand: dna.motion.easing },
      },
    },
  };
  return `// Design DNA "${dna.name}" — Tailwind CSS v3 preset. Usage: presets: [require('./tailwind.preset.js')]\nmodule.exports = ${JSON.stringify(preset, null, 2)};\n`;
}

/** W3C Design Tokens Community Group format (importable into Figma Tokens Studio, Style Dictionary...). */
export function toDtcg(dna) {
  const tokens = tokenMap(dna);
  const out = {};
  const typeOf = (k) => (k.startsWith('color-') ? 'color' : k.startsWith('font-weight') ? 'fontWeight' : k.startsWith('font-') ? 'fontFamily'
    : k.startsWith('shadow-') ? 'shadow' : k === 'duration' ? 'duration' : k.startsWith('ease') ? 'cubicBezier' : 'dimension');
  for (const [k, v] of Object.entries(tokens)) {
    const [group, ...rest] = k.split('-');
    (out[group] ||= {})[rest.join('-') || 'value'] = { $value: v, $type: typeOf(k) };
  }
  return JSON.stringify({ $description: `Design DNA ${dna.name}`, ...out }, null, 2);
}

const roleVar = (v) => (v == null ? null : String(v).startsWith('#') ? v : `var(--color-${v})`);

